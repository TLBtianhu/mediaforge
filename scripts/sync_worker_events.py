"""Generate the frontend worker-event union from manifest/protocol.json.

The frontend must not keep a hand-written copy of the canonical event names:
`src/utils/taskEvents.ts` types its sets with the generated union, so a typo or a
removed event fails `pnpm build` / `tsc` instead of silently never matching.

Usage:
    python scripts/sync_worker_events.py          # rewrite the generated file
    python scripts/sync_worker_events.py --check  # fail if it is out of date
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "manifest" / "protocol.json"
OUTPUT = ROOT / "src" / "types" / "workerEvents.generated.ts"

EVENT_NAME = re.compile(r"^(task|asset)\.[a-z][a-z0-9_]*$")


def canonical_events(manifest: dict) -> list[str]:
    events = (manifest.get("events") or {}).get("canonical") or []
    malformed = [name for name in events if not isinstance(name, str) or not EVENT_NAME.fullmatch(name)]
    if malformed:
        raise ValueError(f"Malformed canonical events: {malformed}")
    if len(set(events)) != len(events):
        raise ValueError("Duplicate canonical events")
    return list(events)


def render_events(events: list[str]) -> str:
    lines = [
        "// Generated by scripts/sync_worker_events.py from manifest/protocol.json.",
        "// Do not edit by hand; run the script after changing the protocol.",
        "export const CANONICAL_WORKER_EVENTS = [",
    ]
    lines.extend(f"  '{name}'," for name in events)
    lines.extend([
        "] as const",
        "",
        "export type CanonicalWorkerEvent = (typeof CANONICAL_WORKER_EVENTS)[number]",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    rendered = render_events(canonical_events(manifest))
    if "--check" in sys.argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if current != rendered:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date; run scripts/sync_worker_events.py")
            return 1
        print(f"{len(canonical_events(manifest))} canonical events")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
