#!/usr/bin/env bash
# Source this only from disposable release probes, never from the desktop launcher.
PROBE_DATA_ROOT="${1:?A disposable probe root is required}"
case "$PROBE_DATA_ROOT" in
  /*) ;;
  *) echo 'The release probe root must be absolute' >&2; return 1 ;;
esac
if [[ "$PROBE_DATA_ROOT" == / ]]; then return 1; fi
unset PYTHONPATH PYTHONHOME
export PYTHONDONTWRITEBYTECODE=1 PYTHONNOUSERSITE=1
export HOME="$PROBE_DATA_ROOT/profile" USERPROFILE="$PROBE_DATA_ROOT/profile"
export MEDIAFORGE_DATA_ROOT="$PROBE_DATA_ROOT/data" MEDIAFORGE_DATA_DIR="$PROBE_DATA_ROOT/data"
export PYMSS_STUDIO_DATA_ROOT="$MEDIAFORGE_DATA_ROOT" PYMSS_STUDIO_DATA_DIR="$MEDIAFORGE_DATA_ROOT"
export MEDIAFORGE_MODEL_DIR="$PROBE_DATA_ROOT/models" PYMSS_MODEL_DIR="$PROBE_DATA_ROOT/models"
export PYMSS_STUDIO_MODEL_DIR="$MEDIAFORGE_MODEL_DIR"
export MEDIAFORGE_RUNTIME_ENVS_DIR="$PROBE_DATA_ROOT/data/runtime-envs"
export PYMSS_STUDIO_RUNTIME_ENVS_DIR="$MEDIAFORGE_RUNTIME_ENVS_DIR"
export MEDIAFORGE_ACTIVE_RUNTIME_FILE="$MEDIAFORGE_RUNTIME_ENVS_DIR/active-runtime.json"
export PYMSS_STUDIO_ACTIVE_RUNTIME_FILE="$MEDIAFORGE_ACTIVE_RUNTIME_FILE"
export WEBVIEW2_USER_DATA_FOLDER="$PROBE_DATA_ROOT/webview"
export XDG_CACHE_HOME="$PROBE_DATA_ROOT/cache" XDG_CONFIG_HOME="$PROBE_DATA_ROOT/config" XDG_DATA_HOME="$PROBE_DATA_ROOT/state"
export HF_HOME="$XDG_CACHE_HOME/huggingface" HF_HUB_CACHE="$XDG_CACHE_HOME/huggingface/hub"
export HUGGINGFACE_HUB_CACHE="$HF_HUB_CACHE" TRANSFORMERS_CACHE="$XDG_CACHE_HOME/transformers"
export HF_ASSETS_CACHE="$HF_HOME/assets" HF_XET_CACHE="$HF_HOME/xet" MODELSCOPE_CACHE="$XDG_CACHE_HOME/modelscope"
export TORCH_HOME="$XDG_CACHE_HOME/torch" TORCH_EXTENSIONS_DIR="$XDG_CACHE_HOME/torch-extensions"
export PIP_CACHE_DIR="$XDG_CACHE_HOME/pip" MPLCONFIGDIR="$XDG_CACHE_HOME/matplotlib"
export NUMBA_CACHE_DIR="$XDG_CACHE_HOME/numba" TRITON_CACHE_DIR="$XDG_CACHE_HOME/triton"
export HF_HUB_OFFLINE=1 TRANSFORMERS_OFFLINE=1 MODELSCOPE_OFFLINE=1
export TMPDIR="$PROBE_DATA_ROOT/tmp" TMP="$PROBE_DATA_ROOT/tmp" TEMP="$PROBE_DATA_ROOT/tmp"
mkdir -p "$HOME" "$MEDIAFORGE_DATA_ROOT" "$MEDIAFORGE_MODEL_DIR" "$MEDIAFORGE_RUNTIME_ENVS_DIR" "$XDG_CACHE_HOME" "$TMPDIR"
